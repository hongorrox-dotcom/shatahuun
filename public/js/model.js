export const TAX_HIST = { tax: 25700, customs: 0, vat: 0.1 };
export function simulate(p) {
  p = Object.assign({}, DEFAULTS, p);
  const T0 = 2014, T1 = 2035;
  let car = 740445, pop = 2.99595e6, gdp = 2.22271e13, reserve = 686200, price = 1660;
  let lagPrev = null, d1 = null; // DELAY FIXED-ийн өмнөх оролт, DELAY1-ийн түвшин
  const out = [];
  for (let t = T0; t <= T1; t++) {
    const usd = lk(LK.usd, t);
    const hil = (167.59 + 1.00739 * lk(LK.world, t)) * usd;
    const gdpRate = lk(LK.gdpRate, t);
    const money = gdp * lk(LK.msShare, t);
    const infl = 9.3925 + 0.00878099 * price - 4.20928e-5 * money / 1e9 + 0.0881477 * gdpRate * 100 - 0.00809098 * usd;
    const infLag = lagPrev === null ? 1 : lagPrev;
    if (d1 === null) d1 = infl / 1000 * 5;
    const infEffect = d1 / 5;
    const gdpGrowth = gdp * (gdpRate - (t >= 2026 ? infEffect : 0));
    const perCap = t <= 2024 ? gdp / pop : gdp * (1 + p.gdpShare) / pop;
    const income = 172676 + perCap * 0.10825;
    const newCars = -112433 + 0.026848 * income + 0.046 * pop;
    const removed = car * lk(LK.removed, t);
    const autos = car * lk(LK.fuelShare, t);
    const ptShare = lk(LK.ptShare, t);
    const ptCount = p.tankYear <= t ? car * ptShare * (1 + p.ptIncrease) : car * ptShare;
    const ptNow = car * ptShare;
    const perCar = lk(LK.perCar, t);
    const saved = lk(LK.ptProb, ptCount) * autos * perCar - lk(LK.ptProb, ptNow) * autos * perCar;
    const consumption = autos * perCar - saved;
    const pulse = t - 1 === p.tankYear ? 1 : 0;
    const tank = (t <= p.tankYear ? 0 : p.tankSize) * pulse;
    const tankBudget = (t <= p.tankYear ? 0 : p.invest) * pulse;
    const supply = lk(LK.imp, t) + tank;
    const mgmt = lk(LK.brand, t) + lk(LK.otherMgmt, t) + lk(LK.mgmtFee, t) + lk(LK.mgmtWage, t);
    const storage = lk(LK.storage, t) + lk(LK.assetRent, t);
    const stc = lk(LK.util, t) + lk(LK.tech, t) + lk(LK.rent, t) + lk(LK.stcWage, t) + lk(LK.stcOther, t) + lk(LK.sales, t);
    const opBase = mgmt + storage + hil * 0.008 + stc;
    const opCost = (p.opYear <= t ? opBase + p.margin : opBase) * infLag;
    const taxOn = t >= p.taxYear;
    const tax = taxOn ? p.excise + p.fuelTax : TAX_HIST.tax;
    const customs = taxOn ? p.customs : TAX_HIST.customs, vat = taxOn ? p.vat : TAX_HIST.vat;
    const base = hil * customs + tax + opCost + lk(LK.autoTransport, t) + lk(LK.rail, t) + hil * 0.01 + hil;
    // 2026 оноос инфляцийн хоцрогдлоор үржинэ, түүнээс өмнө үржихгүй
    const cost = (base + base * vat) / 1000 * 0.76 * (t >= 2026 ? infLag : 1);
    const fluct = t >= 2026 ? -reserve / 5000 + cost * 0.1 : lk(LK.fluct, t);
    out.push({ t, infl, price, reserve, car, ptCount, autos, tank, cost, opCost, tax, tankBudget, consumption, supply });
    const births = pop * lk(LK.birth, t), mig = pop * lk(LK.migr, t), deaths = pop * lk(LK.death, t);
    const popRate = t < 2025 ? births + mig - deaths : (births + mig - deaths) * (1 - pop / p.popCap);
    car += newCars - removed; pop += popRate; gdp += gdpGrowth; reserve += supply - consumption; price += fluct;
    d1 += infl / 1000 - d1 / 5; lagPrev = 1 + infl / 100;
  }
  return out;
}
